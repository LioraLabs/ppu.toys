    let mut value: serde_json::Value = serde_json::from_str(SAMPLE_PPU_JSON).unwrap();
    value["files"]
        .as_array_mut()
        .unwrap()
        .push(serde_json::json!({ "name": "../evil.lua", "source": "-- evil" }));
    let text = serde_json::to_string(&value).unwrap();

