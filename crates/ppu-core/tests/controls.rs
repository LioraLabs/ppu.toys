/// An error exit from the program's own `frame()` body — right after
/// an explicit `apply_pokes()` call it made — must restore the controls
/// undo log before returning, or that call's writes bake in permanently:
/// the next frame's `__ppu_controls_begin` discards the stale log without
/// ever undoing it.
#[test]
fn program_frame_error_after_explicit_apply_pokes_restores_the_undo_log() {
    let main = "function frame(t, f)\n\
                  obj[0].x = obj[0].x + 1\n\
                  apply_pokes()\n\
                  if f == 2 then error(\"boom\") end\n\
                end\n";
    let mut e = LuaEngine::new();
    e.set_sources(&[
        ("main.lua", main),
        ("ppuglobals.lua", &controls("  obj[0].x = 96\n")),
    ])
    .unwrap();

    for f in 0..=4u32 {
        let res = e.frame(0.0, f);
        if f == 2 {
            assert_eq!(res.unwrap_err().file.as_deref(), Some("main.lua"));
        } else {
            res.unwrap();
        }
    }

    e.set_sources(&[("main.lua", main), ("ppuglobals.lua", &controls(""))])
        .unwrap();
    for f in 5..=7u32 {
        e.frame(0.0, f).unwrap();
    }
    // Every frame 0..=4 ran its own `obj[0].x = obj[0].x + 1` exactly once,
    // including frame 2 (it errored only AFTER that increment) — 5
    // increments landed by the time controls is released at frame 5.
    // Frames 5,6,7 add 3 more: 5 + 3 = 8. Without the error-exit restore, frame 2's
    // explicit apply_pokes() write (96) is never undone (baked in instead
    // of restored to 3, its pre-error value), so the count instead lands at
    // 96 + 1 (frame 3) + 1 (frame 4) + 1 (frame 5) + 1 (frame 6) + 1 (frame
    // 7) = 101.
    assert_eq!(
        e.memory().oam[0].x,
        8,
        "the errored frame's explicit apply_pokes() write must have been undone"
    );
}

