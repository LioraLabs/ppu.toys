/// An error exit from the program's own `frame()` body — right after
/// an explicit `apply_pokes()` call it made — must restore the controls
/// undo log before returning, or that call's writes bake in permanently:
/// the next frame's `__ppu_controls_begin` discards the stale log without
/// ever undoing it.
#[test]
fn program_frame_error_after_explicit_apply_pokes_restores_the_undo_log() {
    let main = "function frame(t, f)\n\
                  obj[0].x = obj[0].x + 1\n\
                  apply_pokes()\n\
                  if f == 2 then error(\"boom\") end\n\
                end\n";
    let mut e = LuaEngine::new();
    e.set_sources(&[
        ("main.lua", main),
        ("controls.lua", &controls("  obj[0].x = 96\n")),
    ])
    .unwrap();

    for f in 0..=4u32 {
        let res = e.frame(0.0, f);
        if f == 2 {
            assert_eq!(res.unwrap_err().file.as_deref(), Some("main.lua"));
        } else {
            res.unwrap();
        }
    }

    e.set_sources(&[("main.lua", main), ("controls.lua", &controls(""))])
        .unwrap();
    for f in 5..=7u32 {
        e.frame(0.0, f).unwrap();
    }
    // Every frame 0..=4 ran its own `obj[0].x = obj[0].x + 1` exactly once,
    // including frame 2 (it errored only AFTER that increment) — 5
    // increments landed by the time controls is released at frame 5.
    // Frames 5,6,7 add 3 more: 5 + 3 = 8. Without the error-exit restore, frame 2's
    // explicit apply_pokes() write (96) is never undone (baked in instead
    // of restored to 3, its pre-error value), so the count instead lands at
    // 96 + 1 (frame 3) + 1 (frame 4) + 1 (frame 5) + 1 (frame 6) + 1 (frame
    // 7) = 101.
    assert_eq!(
        e.memory().oam[0].x,
        8,
        "the errored frame's explicit apply_pokes() write must have been undone"
    );
}

/// Same as above, but the explicit `apply_pokes()` call and the error
/// happen inside a `timer(...)` hook instead of `frame()`'s own body — the
/// other error exit after `__ppu_controls_begin` (through
/// `render_frame_audio`) must restore just as reliably.
#[test]
fn timer_hook_error_after_explicit_apply_pokes_restores_the_undo_log() {
    let main = "timer(0, 64, function()\n\
                  apply_pokes()\n\
                  if f_now == 2 then error(\"boom\") end\n\
                end)\n\
                function frame(t, f)\n\
                  f_now = f\n\
                  obj[0].x = obj[0].x + 1\n\
                end\n";
    let mut e = LuaEngine::new();
    e.set_sources(&[
        ("main.lua", main),
        ("controls.lua", &controls("  obj[0].x = 96\n")),
    ])
    .unwrap();

    for f in 0..=4u32 {
        let res = e.frame(0.0, f);
        if f == 2 {
            assert_eq!(res.unwrap_err().file.as_deref(), Some("main.lua"));
        } else {
            res.unwrap();
        }
    }

    e.set_sources(&[("main.lua", main), ("controls.lua", &controls(""))])
        .unwrap();
    for f in 5..=7u32 {
        e.frame(0.0, f).unwrap();
    }
    // Same arithmetic as the frame()-body variant above: 5 increments landed
    // by release (frame 2's increment ran before its timer hook errored),
    // plus 3 more after release = 8, not 101.
    assert_eq!(
        e.memory().oam[0].x,
        8,
        "the timer hook's explicit apply_pokes() write must have been undone"
    );
}

/// The end-of-frame restore must undo controls's writes BEFORE
/// re-baselining sticky globals to the frame-wide defaults, not after: a
/// controls BAND hook's first logged write for a key carries that row's
/// `write_state(row)` baseline as its "old" value, not the frame-wide
/// default, so restoring AFTER `write_state(&defaults)` clobbers the
/// program's own accumulator with a stray per-row value.
#[test]
fn controls_restore_runs_before_the_sticky_defaults_rebaseline() {
    let main = "function frame(t, f)\n\
                  bg[1].scroll.x = bg[1].scroll.x + 1\n\
                  bg[2].scroll.x = bg[1].scroll.x\n\
                  hdma(0, 10, function(y) bg[1].scroll.x = 0 end)\n\
                end\n";
    let doc = controls_with_scanlines(
        "  water = { first = 5, last = 8 },\n",
        "  hdma(scanlines.water.first, scanlines.water.last, function(y)\n\
           bg[1].scroll.x = 50\n\
         end)\n",
    );
    let mut e = LuaEngine::new();
    e.set_sources(&[("main.lua", main), ("controls.lua", &doc)])
        .unwrap();
    e.frame(0.0, 0).unwrap();
    let lt = e.frame(0.0, 1).unwrap();

    assert_eq!(
        lt.rows[0].bg[1].scroll_x, 2,
        "the program's own accumulator (mirrored into bg[2], which nothing \
         pokes) should have advanced 1 -> 2 across the two frames; with the \
         restore-after-rebaseline bug it reads 1"
    );
    assert_eq!(
        lt.rows[6].bg[0].scroll_x, 50,
        "inside the controls band, the band hook still wins"
    );
    assert_eq!(
        lt.rows[0].bg[0].scroll_x, 0,
        "outside the band but inside the program's own hdma, its hook still wins"
    );

    // Baseline sanity: the same program with no controls.lua at all must
    // reach the same accumulator value, proving the 2 above is the program's
    // own arithmetic and not an artifact of controls.
    let mut plain = LuaEngine::new();
    plain.set_sources(&[("main.lua", main)]).unwrap();
    plain.frame(0.0, 0).unwrap();
    let lt = plain.frame(0.0, 1).unwrap();
    assert_eq!(lt.rows[0].bg[1].scroll_x, 2);
}
