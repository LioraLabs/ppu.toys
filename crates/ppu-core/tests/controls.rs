//! Automatic controls application (PPU-147): with a `ppuglobals.lua` in the
//! file list, its `apply_pokes` applies every frame as a final visual
//! override pass — registers on every line, OAM/CGRAM/VRAM in `memory()` —
//! program state is untouched by it (an override never bakes into the
//! program's own baseline or compounds an accumulator), a controls-only
//! `set_sources` never recompiles, and a broken controls edit is refused
//! while the last valid controls keep applying. Driven entirely through
//! `LuaEngine`'s public API (`set_sources`/`frame`/`memory`/`audio`,
//! `LineTable.rows[y]`) — never reaching into the VM.
mod common;
use ppu_core::LuaEngine;

/// A hand-copied fixture of the document shape `web/src/studio/pokes/controls.ts`
/// (PPU-146) generates — NOT a cross-language contract test; the TS
/// generator can drift from this without either side failing here.
/// `markers`/`scanlines` stay present (empty) even when `body` doesn't use
/// them.
fn controls(body: &str) -> String {
    controls_with_scanlines("", body)
}

/// Same as `controls`, but with `scanlines_body` spliced into the
/// `scanlines = {...}` table instead of leaving it empty — for tests whose
/// `apply_pokes` references `scanlines.<name>.first`/`.last`.
fn controls_with_scanlines(scanlines_body: &str, body: &str) -> String {
    format!(
        "-- ppuglobals.lua · generated by the Studio panels. Edit values here or in the panels.\n\
         -- timeline: end=30 in=0 out=30 loop=false\n\
         -- loop markers: in= out=\n\
         markers = {{\n}}\n\
         \n\
         scanlines = {{\n{scanlines_body}}}\n\
         \n\
         function apply_pokes()\n\
         {body}\
         end\n"
    )
}

/// Same as `controls_with_scanlines`, but with the `pk`/`pki`/`pkf`
/// per-scanline-poke preamble spliced immediately before `apply_pokes` — the
/// shape the generated document takes when any keyframe curve is present.
/// Verbatim copy of the preamble text in `scanline_pokes.rs`'s `GENERATED`
/// (from `-- Per-scanline pokes:` through the `pkf` one-liner) — keep it
/// byte-identical to that.
fn controls_with_curve(scanlines_body: &str, body: &str) -> String {
    const PREAMBLE: &str = r#"-- Per-scanline pokes: keyframes {{y,value},…} interpolated down the frame,
-- holding the end values outside the keyframed range.
local function pke(t, easing)
  if easing == "smooth" then return t * t * (3 - 2 * t) end
  if easing == "ease-in" then return t * t end
  if easing == "ease-out" then return t * (2 - t) end
  if easing == "step" then return t < 1 and 0 or 1 end
  return t
end
local function pk(kf, y)
  local n = #kf
  if y <= kf[1][1] then return kf[1][2] end
  for i = 2, n do
    local a, b = kf[i - 1], kf[i]
    if y <= b[1] then
      local d = b[1] - a[1]
      if d <= 0 then return b[2] end
      return a[2] + (b[2] - a[2]) * pke((y - a[1]) / d, a[3])
    end
  end
  return kf[n][2]
end
local function pki(kf, y) return floor(pk(kf, y) + 0.5) end
local function pkf(kf, y) return pk(kf, y) end
"#;
    controls_with_scanlines(scanlines_body, body).replacen(
        "function apply_pokes()",
        &format!("{PREAMBLE}function apply_pokes()"),
        1,
    )
}

/// BRR/directory poke helpers, copied from `dsp_timers.rs` (see that file's
/// doc comment for the layout) — a sounding voice 0 for the controls-only
/// reload / invalid-controls / runtime-error tests, which must prove the DSP
/// keeps running underneath a controls-only push.
fn brr_pokes(base: u16, blocks: usize, last_header: u8) -> String {
    let mut s = String::new();
    for b in 0..blocks {
        let addr = base as usize + b * 9;
        let header = if b == blocks - 1 { last_header } else { 0xc0 };
        s += &format!("aram[{addr}] = {header}\n");
        for (i, byte) in [0x77u8, 0x77, 0x77, 0x77, 0x99, 0x99, 0x99, 0x99]
            .iter()
            .enumerate()
        {
            s += &format!("aram[{}] = {byte}\n", addr + 1 + i);
        }
    }
    s
}

fn dir_entry_pokes(index: u8, start: u16, loop_addr: u16) -> String {
    let addr = 0x0100 + index as usize * 4;
    format!(
        "aram[{a0}] = {b0}\naram[{a1}] = {b1}\naram[{a2}] = {b2}\naram[{a3}] = {b3}\n",
        a0 = addr,
        b0 = start & 0xff,
        a1 = addr + 1,
        b1 = (start >> 8) & 0xff,
        a2 = addr + 2,
        b2 = loop_addr & 0xff,
        a3 = addr + 3,
        b3 = (loop_addr >> 8) & 0xff,
    )
}

/// `main.lua` for the audio-continuity tests: `init()` pokes a 6-block
/// looping BRR sample (directory entry 0, ARAM 0x0200) and seeds `n = 0`;
/// a `timer(0, 64, ..)` counts `ticks`; `frame()` advances `n`, mirrors both
/// into `bg[2]`/`bg[3]` scroll so a test can read them back through the
/// LineTable, drives voice 0's registers every frame (matches
/// `dsp_timers.rs`'s known-good VOICE0_SETUP fields), and keys it on at f=0.
fn voice0_main() -> String {
    format!(
        "function init()\n\
           n = 0\n\
         {sample}{dir}\
         end\n\
         timer(0, 64, function() ticks = (ticks or 0) + 1 end)\n\
         function frame(t, f)\n\
           n = n + 1\n\
           bg[2].scroll.x = n\n\
           bg[3].scroll.x = ticks or 0\n\
           voice[0].sample = 0\n\
           voice[0].pitch = 0x1000\n\
           voice[0].vol.l = 127\n\
           voice[0].vol.r = 127\n\
           voice[0].adsr = {{a = 15, d = 0, s = 7, r = 0}}\n\
           dsp.mvol.l = 127\n\
           dsp.mvol.r = 127\n\
           if f == 0 then kon(0) end\n\
         end\n",
        sample = brr_pokes(0x0200, 6, 0xc3),
        dir = dir_entry_pokes(0, 0x0200, 0x0200),
    )
}

fn has_sound(audio: &[i16]) -> bool {
    audio.iter().any(|&s| s != 0)
}

/// (a) A frame-wide controls override beats the program's own per-frame
/// write; releasing it (pushing an empty `apply_pokes`) returns ownership to
/// the program on the very next frame — no `reset()` involved.
#[test]
fn frame_wide_override_beats_the_programs_own_write_and_release_returns_ownership() {
    let main = "function frame(t, f) brightness = 5 end";
    let mut e = LuaEngine::new();
    e.set_sources(&[
        ("main.lua", main),
        ("ppuglobals.lua", &controls("  brightness = 12\n")),
    ])
    .unwrap();
    let lt = e.frame(0.0, 0).unwrap();
    assert_eq!(lt.rows[0].brightness, 12);
    assert_eq!(lt.rows[223].brightness, 12);

    e.set_sources(&[("main.lua", main), ("ppuglobals.lua", &controls(""))])
        .unwrap();
    let lt = e.frame(0.0, 1).unwrap();
    assert_eq!(
        lt.rows[0].brightness, 5,
        "release should return ownership to the program"
    );
}

/// (b) Overriding an animated property and then releasing it must not bake
/// the override into the program's own baseline or compound its
/// accumulator: `obj[0].x` is both the program's OWN accumulator (it
/// increments itself) and something controls overrides — after release the
/// program's progression must be exactly what it would have been had
/// controls never run.
#[test]
fn releasing_an_override_never_bakes_in_or_compounds_the_accumulator() {
    let main = "function frame(t, f)\n\
                  x = (x or 0) + 1\n\
                  bg[1].scroll.x = x\n\
                  obj[0].x = obj[0].x + 1\n\
                end\n";
    let mut e = LuaEngine::new();
    e.set_sources(&[
        ("main.lua", main),
        (
            "ppuglobals.lua",
            &controls("  bg[1].scroll.x = 100\n  obj[0].x = 96\n"),
        ),
    ])
    .unwrap();

    for f in 0..5u32 {
        let lt = e.frame(0.0, f).unwrap();
        assert_eq!(
            lt.rows[0].bg[0].scroll_x, 100,
            "frame {f}: override should be visible"
        );
        assert_eq!(
            e.memory().oam[0].x,
            96,
            "frame {f}: override should be visible in memory"
        );
    }

    e.set_sources(&[("main.lua", main), ("ppuglobals.lua", &controls(""))])
        .unwrap();
    let lt = e.frame(0.0, 5).unwrap();
    assert_eq!(
        lt.rows[0].bg[0].scroll_x, 6,
        "the program's own x should be exactly 6 (5 prior frames + this one), not 106"
    );
    assert_eq!(
        e.memory().oam[0].x,
        6,
        "the program's own obj[0].x should be exactly 6, not 102"
    );
}

/// (c) A controls frame-wide override composes with the program's OWN
/// authored `hdma`: within the hook's range the hook's own value for a
/// property controls didn't touch survives; outside it, the property that
/// was never overridden by anything shows the frame-wide default.
#[test]
fn frame_wide_override_composes_with_the_programs_own_hdma() {
    let main = "function frame(t, f)\n\
                  brightness = 9\n\
                  hdma(100, 150, function(y)\n\
                    bg[1].scroll.x = 7\n\
                    brightness = 3\n\
                  end)\n\
                end\n";
    let mut e = LuaEngine::new();
    e.set_sources(&[
        ("main.lua", main),
        ("ppuglobals.lua", &controls("  bg[1].scroll.x = 24\n")),
    ])
    .unwrap();
    let lt = e.frame(0.0, 0).unwrap();

    for y in [10usize, 120, 200] {
        assert_eq!(
            lt.rows[y].bg[0].scroll_x, 24,
            "row {y}: controls always wins bg1 scroll x"
        );
    }
    assert_eq!(
        lt.rows[120].brightness, 3,
        "inside main's own hdma range, its own write survives"
    );
    assert_eq!(
        lt.rows[10].brightness, 9,
        "outside it, the frame-wide default (controls didn't touch it)"
    );
}

/// (d) Memory precedence: a controls override on one field of a poke surface
/// (VRAM word, CGRAM entry, one OAM property) overlays only what it touches,
/// leaving the program's other pokes on the same surfaces untouched;
/// releasing restores exactly the program's own memory state.
#[test]
fn memory_precedence_overlays_only_what_controls_touches() {
    let main = "function frame(t, f)\n\
                  vram[0x1000] = 0x1111\n\
                  vram[0x1001] = 0x3333\n\
                  cgram[1] = 0x0001\n\
                  obj[0].tile = 7\n\
                end\n";
    let mut e = LuaEngine::new();
    e.set_sources(&[
        ("main.lua", main),
        (
            "ppuglobals.lua",
            &controls("  vram[0x1000] = 0x2222\n  cgram[1] = 0x7fff\n  obj[0].x = 96\n"),
        ),
    ])
    .unwrap();
    e.frame(0.0, 0).unwrap();
    assert_eq!(e.memory().vram[0x1000], 0x2222);
    assert_eq!(
        e.memory().vram[0x1001],
        0x3333,
        "untouched by controls, main's write survives"
    );
    assert_eq!(e.memory().cgram[1], 0x7fff);
    assert_eq!(
        e.memory().oam[0].tile,
        7,
        "untouched by controls, main's write survives"
    );
    assert_eq!(e.memory().oam[0].x, 96);

    e.set_sources(&[("main.lua", main), ("ppuglobals.lua", &controls(""))])
        .unwrap();
    e.frame(0.0, 1).unwrap();
    assert_eq!(e.memory().vram[0x1000], 0x1111);
    assert_eq!(e.memory().cgram[1], 0x0001);
    assert_eq!(e.memory().oam[0].x, 0);
}

/// (e) A controls-only `set_sources` never recompiles: the VM, its running
/// voice, the timer phase, and the program's own accumulators all keep
/// going. Contrast: an actual `main.lua` change forces a real recompile
/// (init reruns), proving the fast path really is what preserved state above.
#[test]
fn controls_only_reload_keeps_the_vm_hot_full_recompile_does_not() {
    let main = voice0_main();
    let mut e = LuaEngine::new();
    e.set_sources(&[
        ("main.lua", &main),
        ("ppuglobals.lua", &controls("  brightness = 3\n")),
    ])
    .unwrap();

    let mut lt4 = None;
    for f in 0..5u32 {
        lt4 = Some(e.frame(0.0, f).unwrap());
    }
    let lt4 = lt4.unwrap();
    assert!(
        has_sound(e.audio()),
        "voice 0 should still be sounding after 5 frames"
    );
    let ticks4 = lt4.rows[0].bg[2].scroll_x;

    e.set_sources(&[
        ("main.lua", &main),
        ("ppuglobals.lua", &controls("  brightness = 4\n")),
    ])
    .unwrap();
    let lt5 = e.frame(0.0, 5).unwrap();
    assert_eq!(lt5.rows[0].brightness, 4);
    assert_eq!(
        lt5.rows[0].bg[1].scroll_x, 6,
        "n should have continued from frame 4 (5), not reset to 1"
    );
    assert!(
        lt5.rows[0].bg[2].scroll_x > ticks4,
        "ticks should have continued, not reset"
    );
    assert!(has_sound(e.audio()), "voice 0 should still be sounding");

    // Contrast: a real main.lua change (trailing comment) forces a full
    // recompile — init() reruns, resetting n.
    let main_changed = format!("{main}-- trailing comment\n");
    e.set_sources(&[
        ("main.lua", &main_changed),
        ("ppuglobals.lua", &controls("  brightness = 4\n")),
    ])
    .unwrap();
    let lt6 = e.frame(0.0, 6).unwrap();
    assert_eq!(
        lt6.rows[0].bg[1].scroll_x, 1,
        "init should have rerun, resetting n"
    );
}

/// (f) A syntax error in a controls-only push is refused, attributed to
/// `ppuglobals.lua`, and leaves the previously-applying controls (and all
/// program state) exactly as they were; a subsequent valid push recovers.
#[test]
fn invalid_controls_keeps_the_previous_override_and_program_state() {
    let main = voice0_main();
    let mut e = LuaEngine::new();
    e.set_sources(&[
        ("main.lua", &main),
        ("ppuglobals.lua", &controls("  brightness = 4\n")),
    ])
    .unwrap();
    for f in 0..5u32 {
        e.frame(0.0, f).unwrap();
    }

    let broken =
        "markers = {\n}\n\nscanlines = {\n}\n\nfunction apply_pokes(\n  brightness = 9\nend\n";
    let err = e
        .set_sources(&[("main.lua", &main), ("ppuglobals.lua", broken)])
        .unwrap_err();
    assert_eq!(err.file.as_deref(), Some("ppuglobals.lua"));

    let lt = e.frame(0.0, 5).unwrap();
    assert_eq!(
        lt.rows[0].brightness, 4,
        "the last valid controls should still apply"
    );
    assert_eq!(
        lt.rows[0].bg[1].scroll_x, 6,
        "n should have kept counting through the failed push"
    );

    e.set_sources(&[
        ("main.lua", &main),
        ("ppuglobals.lua", &controls("  brightness = 6\n")),
    ])
    .unwrap();
    let lt = e.frame(0.0, 6).unwrap();
    assert_eq!(lt.rows[0].brightness, 6);
    assert_eq!(lt.rows[0].bg[1].scroll_x, 7, "n should still be continuous");
}

/// (g) Toy switch (a full recompile with both files different) drops the
/// old controls override outright; a program with no ppuglobals.lua at all
