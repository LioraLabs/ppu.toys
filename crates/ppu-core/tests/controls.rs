/// The end-of-frame restore must undo controls's writes BEFORE
/// re-baselining sticky globals to the frame-wide defaults, not after: a
/// controls BAND hook's first logged write for a key carries that row's
/// `write_state(row)` baseline as its "old" value, not the frame-wide
/// default, so restoring AFTER `write_state(&defaults)` clobbers the
/// program's own accumulator with a stray per-row value.
#[test]
fn controls_restore_runs_before_the_sticky_defaults_rebaseline() {
    let main = "function frame(t, f)\n\
                  bg[1].scroll.x = bg[1].scroll.x + 1\n\
                  bg[2].scroll.x = bg[1].scroll.x\n\
                  hdma(0, 10, function(y) bg[1].scroll.x = 0 end)\n\
                end\n";
    let doc = controls_with_scanlines(
        "  water = { first = 5, last = 8 },\n",
        "  hdma(scanlines.water.first, scanlines.water.last, function(y)\n\
           bg[1].scroll.x = 50\n\
         end)\n",
    );
    let mut e = LuaEngine::new();
    e.set_sources(&[("main.lua", main), ("ppuglobals.lua", &doc)])
        .unwrap();
    e.frame(0.0, 0).unwrap();
    let lt = e.frame(0.0, 1).unwrap();

    assert_eq!(
        lt.rows[0].bg[1].scroll_x, 2,
        "the program's own accumulator (mirrored into bg[2], which nothing \
         pokes) should have advanced 1 -> 2 across the two frames; with the \
         restore-after-rebaseline bug it reads 1"
    );
    assert_eq!(
        lt.rows[6].bg[0].scroll_x, 50,
        "inside the controls band, the band hook still wins"
    );
    assert_eq!(
        lt.rows[0].bg[0].scroll_x, 0,
        "outside the band but inside the program's own hdma, its hook still wins"
    );

    // Baseline sanity: the same program with no ppuglobals.lua at all must
    // reach the same accumulator value, proving the 2 above is the program's
    // own arithmetic and not an artifact of controls.
    let mut plain = LuaEngine::new();
    plain.set_sources(&[("main.lua", main)]).unwrap();
    plain.frame(0.0, 0).unwrap();
    let lt = plain.frame(0.0, 1).unwrap();
    assert_eq!(lt.rows[0].bg[1].scroll_x, 2);
}

