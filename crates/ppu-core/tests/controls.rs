/// (i) A program `hdma` hook missing its function argument (a typo'd
/// `hdma(0, 100)`) must not desync the splice index from the collected
/// hooks Vec — only FUNCTION-bearing `__ppu_hooks` entries are ever
/// collected, so `n_program` must count the same way or the splice index
/// can go out of range. Also proves splice ordering: the frame-wide
/// controls override beats the program's own hdma hook, and controls's own
/// band hook (registered by `apply_pokes` itself) beats the frame-wide
/// override in turn.
#[test]
fn program_hook_missing_its_function_argument_does_not_desync_the_splice_index() {
    let main = "function frame(t, f)\n\
                  brightness = 9\n\
                  hdma(0, 100)\n\
                  hdma(100, 150, function(y) bg[1].scroll.x = 7 end)\n\
                end\n";
    let doc = controls_with_scanlines(
        "  water = { first = 120, last = 223 },\n",
        "  bg[1].scroll.x = 24\n\
         hdma(scanlines.water.first, scanlines.water.last, function(y)\n\
           bg[1].scroll.x = 2\n\
         end)\n",
    );
    let mut e = LuaEngine::new();
    e.set_sources(&[("main.lua", main), ("controls.lua", &doc)])
        .unwrap();
    for f in 0..2u32 {
        let lt = e.frame(0.0, f).unwrap();
        assert_eq!(lt.rows[10].bg[0].scroll_x, 24, "frame {f}");
        assert_eq!(
            lt.rows[110].bg[0].scroll_x, 24,
            "frame {f}: frame-wide beats the program hook"
        );
        assert_eq!(
            lt.rows[125].bg[0].scroll_x, 2,
            "frame {f}: controls band beats frame-wide"
        );
        assert_eq!(lt.rows[110].brightness, 9, "frame {f}");
    }
}

