//! `ppu.d.luau` declares exactly the globals a program sees: every declared name exists at run
//! time, and every global the engine defines for programs is declared.
use ppu_core::{LuaEngine, LUAU_DECLARATIONS};
use std::collections::BTreeSet;

/// Globals programs see but should not write against: the Lua standard library, the generated
/// ppuglobals.lua's own names, and engine plumbing.
const UNDECLARED: &[&str] = &[
    "assert",
    "coroutine",
    "error",
    "ipairs",
    "math",
    "next",
    "pairs",
    "pcall",
    "print",
    "require", // Luau's own: a checker resolves modules (and their types) itself
    "rawequal",
    "rawget",
    "rawlen",
    "rawset",
    "select",
    "setmetatable",
    "getmetatable",
    "string",
    "table",
    "tonumber",
    "tostring",
    "type",
    "unpack",
    "utf8",
    "xpcall",
    "_G",
    "_VERSION",
    // ppuglobals.lua (generated by the Studio panels) defines and calls these.
    "apply_pokes",
    "markers",
    "scanlines",
    "vr",
    "tracked_vr",
    // Retired names that only raise an error saying what replaced them.
    "target",
    "song",
];

fn declared() -> BTreeSet<String> {
    let mut names = BTreeSet::new();
    for line in LUAU_DECLARATIONS.lines() {
        let Some(rest) = line.strip_prefix("declare ") else {
            continue;
        };
        let rest = rest.strip_prefix("function ").unwrap_or(rest);
        let name: String = rest
            .chars()
            .take_while(|c| c.is_alphanumeric() || *c == '_')
            .collect();
        names.insert(name);
    }
    names
}

/// Every name the engine's sources could define as a global: its string literals and the
/// file-level assignments and functions of its Lua preludes.
fn candidates() -> BTreeSet<String> {
    let mut names = BTreeSet::new();
    let rust = include_str!("../src/lua.rs");
    for piece in rust.split('"').skip(1).step_by(2) {
        names.insert(piece.to_string());
    }
    for prelude in [
        include_str!("../src/luau.lua"),
        include_str!("../src/sprites.lua"),
        include_str!("../src/kit.lua"),
        include_str!("../src/hud.lua"),
        include_str!("../src/ramps.lua"),
        include_str!("../src/vram_helpers.lua"),
        include_str!("../src/controls_env.lua"),
    ] {
        for line in prelude.lines() {
            let line = line.strip_prefix("function ").unwrap_or(line);
            names.insert(
                line.chars()
                    .take_while(|c| c.is_alphanumeric() || *c == '_')
                    .collect(),
            );
        }
    }
    names
        .into_iter()
        .filter(|n| {
            !n.is_empty()
                && !n.starts_with("__")
                && !n.starts_with(|c: char| c.is_ascii_digit())
                && n.chars().all(|c| c.is_alphanumeric() || c == '_')
                && !matches!(
                    n.as_str(),
                    "and"
                        | "end"
                        | "for"
                        | "if"
                        | "in"
                        | "local"
                        | "nil"
                        | "not"
                        | "or"
                        | "return"
                        | "then"
                        | "true"
                        | "false"
                        | "while"
                        | "do"
                        | "else"
                        | "elseif"
                        | "repeat"
                        | "until"
                        | "break"
                        | "function"
                        | "goto"
                )
        })
        .collect()
}

/// The subset of `names` that are globals (not nil) in a fresh Luau program.
fn present(names: &BTreeSet<String>) -> BTreeSet<String> {
    // makeBounded and makeFixed are rewritten by the Luau frontend wherever they are written.
    let (constructors, probed): (Vec<_>, Vec<_>) = names
        .iter()
        .partition(|n| matches!(n.as_str(), "makeBounded" | "makeFixed"));
    let mut program = String::from("local found = \"\"\n");
    for n in probed {
        program.push_str(&format!(
            "if {n} ~= nil then found = found .. \" {n}\" end\n"
        ));
    }
    program.push_str("error(\"FOUND\" .. found .. \" END\")\n");
    let mut engine = LuaEngine::new();
    let message = engine
        .set_sources(&[("main.luau", &program)])
        .err()
        .expect("the probe errors")
        .message;
    let list = message
        .split("FOUND")
        .nth(1)
        .and_then(|s| s.split(" END").next())
        .unwrap_or_else(|| panic!("{message}"));
    list.split_whitespace()
        .map(String::from)
        .chain(constructors.into_iter().cloned())
        .collect()
}

#[test]
fn every_declared_global_exists() {
    let declared = declared();
    let missing: Vec<_> = declared.difference(&present(&declared)).cloned().collect();
    assert!(
        missing.is_empty(),
        "ppu.d.luau declares globals the runtime lacks: {missing:?}"
    );
}

#[test]
fn every_runtime_global_is_declared() {
    let declared = declared();
    let undeclared: Vec<_> = present(&candidates())
        .into_iter()
        .filter(|n| !declared.contains(n) && !UNDECLARED.contains(&n.as_str()))
        .collect();
    assert!(
        undeclared.is_empty(),
        "globals missing from ppu.d.luau: {undeclared:?}"
    );
}
